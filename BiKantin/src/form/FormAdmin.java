    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        
String namaMenu = txtNamaMenu.getText().trim();
String kategori = cmbKategori.getSelectedItem().toString();
String hargaText = txtHarga.getText().trim();

if (namaMenu.isEmpty() || hargaText.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Nama menu dan harga harus diisi!");
    return;
}

try {
    int harga = Integer.parseInt(hargaText);

    if (harga <= 0) {
        JOptionPane.showMessageDialog(this,
                "Harga harus lebih dari 0!");
        return;
    }

    String sql = "INSERT INTO menu (nama_menu, harga, kategori) "
            + "VALUES (?, ?, ?)";

    try (Connection conn = koneksi.Koneksi.getConnection()) {
        if (conn == null) {
            JOptionPane.showMessageDialog(this,
                    "Koneksi database gagal!");
            return;
        }

        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, namaMenu);
            ps.setInt(2, harga);
            ps.setString(3, kategori);

            ps.executeUpdate();
        }
    }

    JOptionPane.showMessageDialog(this,
            "Menu berhasil disimpan!");

    loadDataMenu();
    txtNamaMenu.setText("");
    txtHarga.setText("");

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Harga harus berupa angka!");
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Gagal menyimpan menu: " + e.getMessage());
}

    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        
int baris = jTable1.getSelectedRow();

if (baris == -1) {
    JOptionPane.showMessageDialog(this,
            "Pilih menu yang ingin diubah dari tabel!");
    return;
}

String namaMenu = txtNamaMenu.getText().trim();
String hargaText = txtHarga.getText().trim();
String kategori = cmbKategori.getSelectedItem().toString();

if (namaMenu.isEmpty() || hargaText.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Nama menu dan harga harus diisi!");
    return;
}

try {
    int id = Integer.parseInt(
            jTable1.getValueAt(baris, 0).toString());
    int harga = Integer.parseInt(hargaText);

    if (harga <= 0) {
        JOptionPane.showMessageDialog(this,
                "Harga harus lebih dari 0!");
        return;
    }

    String sql = "UPDATE menu SET nama_menu = ?, "
            + "harga = ?, kategori = ? WHERE id = ?";

    try (Connection conn = koneksi.Koneksi.getConnection()) {
        if (conn == null) {
            JOptionPane.showMessageDialog(this,
                    "Koneksi database gagal!");
            return;
        }

        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, namaMenu);
            ps.setInt(2, harga);
            ps.setString(3, kategori);
            ps.setInt(4, id);

            ps.executeUpdate();
        }
    }

    JOptionPane.showMessageDialog(this,
            "Menu berhasil diubah!");

    loadDataMenu();
    txtNamaMenu.setText("");
    txtHarga.setText("");

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Harga harus berupa angka!");
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Gagal mengubah menu: " + e.getMessage());
}

    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        
int baris = jTable1.getSelectedRow();

if (baris == -1) {
    JOptionPane.showMessageDialog(this,
            "Pilih menu yang ingin dihapus dari tabel!");
    return;
}

int konfirmasi = JOptionPane.showConfirmDialog(
        this,
        "Yakin ingin menghapus menu ini?",
        "Konfirmasi Hapus",
        JOptionPane.YES_NO_OPTION
);

if (konfirmasi != JOptionPane.YES_OPTION) {
    return;
}

try {
    int id = Integer.parseInt(
            jTable1.getValueAt(baris, 0).toString());

    String sql = "DELETE FROM menu WHERE id = ?";

    try (Connection conn = koneksi.Koneksi.getConnection()) {
        if (conn == null) {
            JOptionPane.showMessageDialog(this,
                    "Koneksi database gagal!");
            return;
        }

        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setInt(1, id);

            int hasil = ps.executeUpdate();

            if (hasil > 0) {
                JOptionPane.showMessageDialog(this,
                        "Menu berhasil dihapus!");
            } else {
                JOptionPane.showMessageDialog(this,
                        "Menu tidak ditemukan.");
            }
        }
    }

    loadDataMenu();
    txtNamaMenu.setText("");
    txtHarga.setText("");

} catch (SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Gagal menghapus menu: " + e.getMessage());
}

    }//GEN-LAST:event_btnHapusActionPerformed

