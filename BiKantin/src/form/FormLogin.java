private void login(String username, String password) {
    String sql = "SELECT id, username, role FROM users "
            + "WHERE username = ? AND password = ?";

    try (java.sql.Connection conn =
                koneksi.Koneksi.getConnection()) {

        if (conn == null) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Koneksi database gagal.");
            return;
        }

        try (java.sql.PreparedStatement ps =
                    conn.prepareStatement(sql)) {

            ps.setString(1, username);
            ps.setString(2, password);

            try (java.sql.ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    String role = rs.getString("role");

                    if ("admin".equalsIgnoreCase(role)) {
                        javax.swing.JOptionPane.showMessageDialog(
                                this,
                                "Login berhasil sebagai ADMIN.");

                        FormAdmin formAdmin = new FormAdmin();
                        formAdmin.setLocationRelativeTo(null);
                        formAdmin.setVisible(true);
                        this.dispose();

                    } else if ("siswa".equalsIgnoreCase(role)) {
                        javax.swing.JOptionPane.showMessageDialog(
                                this,
                                "Login berhasil sebagai SISWA.");

                        FormSiswa formSiswa = new FormSiswa(username);
                        formSiswa.setLocationRelativeTo(null);
                        formSiswa.setVisible(true);
                        this.dispose();

                    } else {
                        javax.swing.JOptionPane.showMessageDialog(
                                this,
                                "Role akun tidak dikenali.");
                    }

                } else {
                    javax.swing.JOptionPane.showMessageDialog(
                            this,
                            "Username atau password salah.");
                }
            }
        }

    } catch (java.sql.SQLException ex) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Terjadi kesalahan database: "
                        + ex.getMessage());
    }
}
